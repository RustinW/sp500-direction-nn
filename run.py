"""End-to-end pipeline: data -> features -> walk-forward train -> evaluate.

    python run.py            # uses cached data in data/ if present
    python run.py --refresh  # re-download from Yahoo first

Writes everything to outputs/.
"""
from __future__ import annotations

import argparse
import json
import random
import warnings
from dataclasses import asdict

warnings.filterwarnings("ignore", message=".*OpenSSL.*")

import numpy as np
import pandas as pd
import torch

from spdir.backtest import run_backtests
from spdir.config import CFG, OUT_DIR
from spdir.data import load_raw
from spdir.features import make_dataset
from spdir.metrics import per_fold_metrics, pooled_metrics, significance_tests
from spdir.models import set_determinism
from spdir.plots import plot_equity, plot_fold_accuracy
from spdir.walkforward import MODEL_LABELS, MODELS, run_walkforward


def _pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def write_results_md(pooled, folds, tests, bt, vs_bh, fold_info, ds, feature_cols, path) -> None:
    lines = ["# Results (auto-generated by run.py — do not edit by hand)", ""]
    lines += [
        f"- Data: {CFG.ticker} daily, features available {ds.index[0].date()} to {ds.index[-1].date()} ({len(ds)} rows, {len(feature_cols)} features)",
        f"- Out-of-sample: {fold_info[0]['test_start']} to {fold_info[-1]['test_end']}, {len(fold_info)} yearly folds, {int(pooled['n'].iloc[0])} days",
        "",
        "## Pooled out-of-sample classification",
        "",
        "| Model | Accuracy | Balanced acc. | AUC | Predicted up | TN | FP | FN | TP |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for m in MODELS:
        r = pooled.loc[m]
        lines.append(
            f"| {MODEL_LABELS[m]} | {_pct(r.accuracy)} | {_pct(r.balanced_accuracy)} | {r.auc:.3f} | {_pct(r.pred_up_rate)} | {int(r.tn)} | {int(r.fp)} | {int(r.fn)} | {int(r.tp)} |"
        )
    lines += ["", "## Significance tests (one-sided, pooled over all out-of-sample days)", "",
              "| Model | Accuracy (95% CI) | p vs 50% | p vs always-up (binomial) | Discordant days: model right / always-up right | p vs always-up (McNemar exact) |",
              "|---|---|---|---|---|---|"]
    for t in tests:
        lo, hi = t["accuracy_ci95"]
        lines.append(
            f"| {MODEL_LABELS[t['model']]} | {_pct(t['accuracy'])} ({_pct(lo)}–{_pct(hi)}) | {t['p_value_vs_50pct']:.4g} | {t['p_value_vs_always_up_binomial']:.4g} | {t['discordant_model_right']} / {t['discordant_always_up_right']} | {t['p_value_vs_always_up_mcnemar']:.4g} |"
        )
    lines += ["", f"## Long/flat back-test ({CFG.cost_bps:g} bps per trade unless marked gross)", "",
              "| Strategy | Costs | CAGR | Sharpe | Max drawdown | Ann. vol | Time in market | Trades |",
              "|---|---|---|---|---|---|---|---|"]
    names = {"buy_and_hold": "Buy and hold", "mlp": "MLP long/flat", "logreg": "Logistic long/flat", "prev_dir": "Previous-day long/flat"}
    for _, r in bt.iterrows():
        lines.append(
            f"| {names[r.strategy]} | {r.costs} | {_pct(r.cagr)} | {r.sharpe:.2f} | {_pct(r.max_drawdown)} | {_pct(r.ann_vol)} | {_pct(r.time_in_market)} | {int(r.n_trades)} |"
        )
    lines += ["", "## Is the edge over buy-and-hold solid? (net of costs)", "",
              "| Strategy | Flat days | Mean next-day return on flat days | Up-rate on flat days | Paired t-test vs buy-and-hold (one-sided p) | Best single day avoided | CAGR if long on that one day |",
              "|---|---|---|---|---|---|---|"]
    for _, r in vs_bh.iterrows():
        lines.append(
            f"| {names[r.strategy]} | {int(r.flat_days)} | {_pct(r.mean_next_return_on_flat_days)} | {_pct(r.up_rate_on_flat_days)} | t = {r.excess_t_stat:.2f}, p = {r.excess_p_value:.3f} | {_pct(r.best_flat_day_return_avoided)} | {_pct(r.cagr_without_best_flat_day)} |"
        )
    lines += ["", "## MLP early stopping", "",
              "Best epoch per ensemble member (out of a maximum of %d), chosen on the validation slice of the training fold:" % CFG.max_epochs, "",
              "| Test year | Train rows (fit + val) | Best epochs |", "|---|---|---|"]
    for f in fold_info:
        lines.append(f"| {f['year']} | {f['n_fit']} + {f['n_val']} | {', '.join(str(e) for e in f['best_epochs'])} |")
    lines += ["", "## Per-fold metrics", ""]
    for m in MODELS:
        lines += [f"### {MODEL_LABELS[m]}", "",
                  "| Test year | n | Up days | Accuracy | Balanced acc. | AUC | TN | FP | FN | TP |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in folds[folds.model == m].iterrows():
            lines.append(
                f"| {int(r.fold)} | {int(r.n)} | {_pct(r.up_rate)} | {_pct(r.accuracy)} | {_pct(r.balanced_accuracy)} | {r.auc:.3f} | {int(r.tn)} | {int(r.fp)} | {int(r.fn)} | {int(r.tp)} |"
            )
        lines.append("")
    lines += ["Confusion matrix convention: positive class = up. TN = predicted down, was down; FP = predicted up, was down; FN = predicted down, was up; TP = predicted up, was up.", ""]
    path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--refresh", action="store_true", help="re-download data instead of using the cache")
    args = ap.parse_args()

    random.seed(CFG.seed)
    np.random.seed(CFG.seed)
    torch.manual_seed(CFG.seed)
    set_determinism()
    OUT_DIR.mkdir(exist_ok=True)

    raw = load_raw(CFG, refresh=args.refresh)
    ds, feature_cols = make_dataset(raw)
    print(f"raw bars: {len(raw)} ({raw.index[0].date()}..{raw.index[-1].date()}); "
          f"dataset rows: {len(ds)} ({ds.index[0].date()}..{ds.index[-1].date()}); features: {len(feature_cols)}")

    preds, fold_info = run_walkforward(ds, feature_cols, CFG)
    folds = per_fold_metrics(preds)
    pooled = pooled_metrics(preds)
    tests = [significance_tests(preds, m) for m in ("mlp", "logreg", "prev_dir")]
    bt = run_backtests(preds, CFG)

    preds.to_csv(OUT_DIR / "predictions.csv", float_format="%.6f")
    folds.to_csv(OUT_DIR / "fold_metrics.csv", index=False, float_format="%.6f")
    pooled.to_csv(OUT_DIR / "pooled_metrics.csv", float_format="%.6f")
    bt["table"].to_csv(OUT_DIR / "backtest.csv", index=False, float_format="%.6f")
    bt["vs_bh"].to_csv(OUT_DIR / "backtest_vs_buy_and_hold.csv", index=False, float_format="%.6f")
    bt["equity"].to_csv(OUT_DIR / "equity_curves.csv", float_format="%.6f")
    (OUT_DIR / "summary.json").write_text(json.dumps(
        {"config": asdict(CFG), "features": feature_cols, "folds": fold_info,
         "pooled": pooled.reset_index().to_dict(orient="records"),
         "significance": tests, "backtest": bt["table"].to_dict(orient="records"),
         "backtest_vs_buy_and_hold": bt["vs_bh"].to_dict(orient="records")}, indent=2))
    write_results_md(pooled, folds, tests, bt["table"], bt["vs_bh"], fold_info, ds, feature_cols, OUT_DIR / "results.md")
    plot_fold_accuracy(folds, OUT_DIR / "fold_accuracy.png")
    plot_equity(bt["equity"], CFG, OUT_DIR / "equity_curve.png")

    pd.set_option("display.width", 200)
    print("\nPooled out-of-sample metrics:\n", pooled[["n", "accuracy", "balanced_accuracy", "auc", "pred_up_rate"]].round(4))
    print("\nSignificance:")
    for t in tests:
        print(f"  {t['model']:9s} acc={t['accuracy']:.4f}  p(vs 50%)={t['p_value_vs_50pct']:.4g}  "
              f"p(vs always-up, binomial)={t['p_value_vs_always_up_binomial']:.4g}  "
              f"p(vs always-up, McNemar)={t['p_value_vs_always_up_mcnemar']:.4g}")
    print("\nBack-test:\n", bt["table"].round(4).to_string(index=False))
    print("\nVersus buy-and-hold:\n", bt["vs_bh"].round(4).to_string(index=False))
    print(f"\nWrote outputs to {OUT_DIR}")


if __name__ == "__main__":
    main()
