"""How much do the results move between training runs?

    python seed_spread.py

Repeats the whole walk-forward evaluation with a single MLP per fold, each
time from a different random seed, then groups those runs into five-model
averages (the configuration run.py uses). Reports the spread of pooled
out-of-sample accuracy for both, and writes outputs/seed_spread.md.

This is a diagnostic of the method, not a search: nothing here feeds back
into run.py's configuration, and the seeds below are not the ones run.py uses.
"""
from __future__ import annotations

import time
import warnings
from dataclasses import replace

warnings.filterwarnings("ignore", message=".*OpenSSL.*")

import numpy as np

from spdir.config import CFG, OUT_DIR
from spdir.data import load_raw
from spdir.features import make_dataset
from spdir.models import set_determinism
from spdir.walkforward import run_walkforward

FIRST_SEED = 100  # offset added to CFG.seed: these runs use 142..171, run.py uses 42..46
N_RUNS = 30
ENSEMBLE_SIZE = len(CFG.ensemble_seeds)


def _accuracy(prob: np.ndarray, y: np.ndarray) -> float:
    return float(((prob > CFG.threshold).astype(int) == y).mean())


def _row(label: str, acc: np.ndarray) -> str:
    a = 100 * acc
    return (f"| {label} | {len(a)} | {a.mean():.2f}% | {a.std(ddof=1):.2f} | "
            f"{a.min():.2f}% | {a.max():.2f}% | {a.max() - a.min():.2f} |")


def main() -> None:
    set_determinism()
    ds, cols = make_dataset(load_raw(CFG))

    probs, seconds, y = [], [], None
    for seed in range(FIRST_SEED, FIRST_SEED + N_RUNS):
        start = time.time()
        preds, _ = run_walkforward(ds, cols, replace(CFG, ensemble_seeds=(seed,)), verbose=False)
        seconds.append(time.time() - start)
        probs.append(preds["p_mlp"].to_numpy())
        y = preds["y"].to_numpy()
    probs = np.array(probs)

    single = np.array([_accuracy(p, y) for p in probs])
    # Disjoint groups, so the ensembles share no models.
    ensembles = np.array([
        _accuracy(probs[i : i + ENSEMBLE_SIZE].mean(axis=0), y)
        for i in range(0, N_RUNS - ENSEMBLE_SIZE + 1, ENSEMBLE_SIZE)
    ])
    always_up = float(y.mean())

    lines = [
        "# Run-to-run spread (auto-generated by seed_spread.py)",
        "",
        f"Pooled out-of-sample accuracy over {len(y)} days, {N_RUNS} walk-forward runs "
        f"from {N_RUNS} different seeds (none shared with run.py). Always-up scores {100 * always_up:.2f}%.",
        "",
        "| Configuration | Runs | Mean | Std. dev. (pts) | Min | Max | Range (pts) |",
        "|---|---|---|---|---|---|---|",
        _row("Single MLP, new seed each run", single),
        _row(f"Average of {ENSEMBLE_SIZE} MLPs, new seeds each run", ensembles),
        "",
        f"- Single-model runs that beat always-up: {int((single > always_up).sum())} of {len(single)}.",
        f"- {ENSEMBLE_SIZE}-model averages that beat always-up: {int((ensembles > always_up).sum())} of {len(ensembles)}.",
        "- With seeds fixed (run.py), repeated runs on the same machine are identical, so the spread is zero.",
        f"- One single-model walk-forward ({preds['fold'].nunique()} folds) took {np.mean(seconds):.1f} s on average.",
        "",
    ]
    text = "\n".join(lines)
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "seed_spread.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
